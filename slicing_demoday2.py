#Slicing
cart= ['Shirt',"Lamp","Pen","Book","Crayons"]
del cart[:2]
print(cart)

cart= ['Shirt',"Lamp","Pen","Book","Crayons"]
del cart[2:]
print(cart)

cart= ['Shirt',"Lamp","Pen","Book","Crayons"]
del cart[1:3]
print(cart)


cart= ['Shirt',"Lamp","Pen","Book","Crayons"]
del cart[-1:]
print(cart)

cart= ['Shirt',"Lamp","Pen","Book","Crayons"]
del cart[:-2]
print(cart)


