def divide(a, b):
    try:
        result = int(a) / int(b)
    except ValueError:
        print("Please enter numbers only.")
    except ZeroDivisionError:
        print("Cannot divide by zero.")
    else:
        print("Result:", result)
    finally:
        print("-- divide() finished --")

divide("10", "2")   # Result: 5.0
divide("10", "0")   # Cannot divide by zero.
divide("ten", "2")  # Please enter numbers only.

