# – raise built-in exceptions
def set_age(age):
  if not isinstance(age, int):
     raise TypeError("Age must be an integer")
  if age < 0:
    raise ValueError(f"Age cannot be negative: {age}")
  return age


for a in [25, -5, "abc"]:
  try:
    print("Age set to", set_age(a))
  except (ValueError, TypeError) as e:
     print("Rejected:", e)

